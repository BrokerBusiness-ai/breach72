"""Build the four SYNTHETIC source systems that Zetaris federates.

Writes docker/sources/init/*.sql for one PostgreSQL container with four separate
databases, one per source system of a public body:

  incident_db   incident log, updates, access logs, export items (from seed_postgres.sql)
  ropa_db       record of processing activities (ropa.csv)
  asset_db      asset and encryption register (assets.csv)
  contracts_db  processor contracts (processor_contracts.csv)

Zetaris registers each database as its own datasource, so every agent question that
spans systems is answered by one federated SQL query through Zetaris.
All data is synthetic (data/generator.py).
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYN = ROOT / "data" / "synthetic"
OUT = ROOT / "docker" / "sources" / "init"
INT_COLS = {"bytes", "records_count", "case_no", "subjects_estimate", "breach_notice_hours"}


def lit(v: str, col: str) -> str:
    if v == "":
        return "NULL"
    if col in INT_COLS:
        return str(int(v))
    return "'" + v.replace("'", "''") + "'"


def csv_sql(name: str) -> str:
    with open(SYN / f"{name}.csv", encoding="utf-8", newline="") as fh:
        rows = list(csv.reader(fh))
    cols = rows[0]
    out = [f"DROP TABLE IF EXISTS {name};",
           f"CREATE TABLE {name} (" + ", ".join(f"{c} {'BIGINT' if c in INT_COLS else 'TEXT'}" for c in cols) + ");"]
    for r in rows[1:]:
        out.append(f"INSERT INTO {name} VALUES (" + ", ".join(lit(v, c) for v, c in zip(r, cols)) + ");")
    return "\n".join(out) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    head = "-- SYNTHETIC DATA. Generated by scripts/zetaris_sources.py.\n"
    (OUT / "00_databases.sql").write_text(
        head + "".join(f"CREATE DATABASE {d};\n" for d in ("incident_db", "ropa_db", "asset_db", "contracts_db")),
        encoding="utf-8")
    seed = (SYN / "seed_postgres.sql").read_text(encoding="utf-8")
    # seed_postgres.sql holds all seven tables; keep only the incident-log system here
    keep, block, cur = [], [], None
    for line in seed.splitlines():
        if line.startswith("DROP TABLE IF EXISTS "):
            cur = line.split()[-1].rstrip(";")
        if cur in ("incidents", "incident_updates", "access_logs", "export_items"):
            keep.append(line)
    (OUT / "10_incident_db.sql").write_text(head + "\\c incident_db\n" + "\n".join(keep) + "\n", encoding="utf-8")
    (OUT / "20_ropa_db.sql").write_text(head + "\\c ropa_db\n" + csv_sql("ropa"), encoding="utf-8")
    (OUT / "30_asset_db.sql").write_text(head + "\\c asset_db\n" + csv_sql("assets"), encoding="utf-8")
    (OUT / "40_contracts_db.sql").write_text(head + "\\c contracts_db\n" + csv_sql("processor_contracts"),
                                             encoding="utf-8")
    for p in sorted(OUT.glob("*.sql")):
        print(p.name, p.stat().st_size)


if __name__ == "__main__":
    main()
